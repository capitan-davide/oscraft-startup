#!/usr/bin/env python3
"""Write layout.txt from the object compiled from layout.c.

Usage: layout.py <nm> <layout.o> <layout.txt>

<nm> is the SDP's nm for AArch64 (ntoaarch64-nm). Each symbol
abi__<Type>__<field> has the size <value> + 1, where <value> is the field's
offset, or the type's size for the field "size". The output has one
"<Type>.<field> <value>" line per symbol, sorted, which the Rust test
src/abi/layout_tests.rs checks the Rust types against.
"""

import subprocess
import sys

nm, obj, out = sys.argv[1:]
lines = []
for line in subprocess.run([nm, "-S", obj], check=True, capture_output=True,
                           text=True).stdout.splitlines():
    fields = line.split()
    if len(fields) != 4 or not fields[3].startswith("abi__"):
        continue
    rust_type, field = fields[3][len("abi__"):].split("__", 1)
    lines.append(f"{rust_type}.{field} {int(fields[1], 16) - 1}")

with open(out, "w") as f:
    f.write("# Generated by layout.py from layout.c and the QNX SDP 8.0 headers.\n")
    f.write("# Regenerate with 'make abi-layout'; do not edit.\n")
    f.write("".join(l + "\n" for l in sorted(lines)))
